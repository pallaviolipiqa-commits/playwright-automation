"use strict";
//Sample code demonstrating the use of primitive data types in TypeScript
//String data type
let userName = "Alice";
//Number data type
let userAge = 30;
//Boolean data type
let isAdmin = true;
//Symbol data type
let userSymbol = Symbol("user");
//null data type
let userNull = null;
//undefined data type
let userUndefined = undefined;
console.log("User Name is", userName);
console.log("User Age is", userAge);
console.log("Is Admin?", isAdmin);
console.log("User Symbol is", userSymbol.toString());
console.log("User Null is", userNull);
console.log("User Undefined is", userUndefined);
