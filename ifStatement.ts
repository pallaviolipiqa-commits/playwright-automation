
//Find the marks of an student and print the grade based on the following criteria:
let marks : number = 35;
if (marks >= 90 && marks <= 100) {
    console.log("Grade: A");
} else if (marks > 35 && marks < 90) {
    console.log("Grade: B");
} else if (marks <= 35 && marks >=0) {
    console.log("Grade: C");
} else {
    console.log("Enter Valid Marks");
}   

